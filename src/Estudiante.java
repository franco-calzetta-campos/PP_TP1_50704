public class Estudiante {
    private String legajo;
    private String nombre;

    public String getLegajo() {
        return this.legajo;
    }
    public void setLegajo(String legajo) {
        this.legajo = legajo;
    }

    public String getNombre() {
        return this.nombre;
    }
    public void setNombre(String nombre) {
        this.nombre = nombre;
    }
}
